/**
 * Translation status, metadata, and node schemas for localized content.
 *
 * ## The translations/ directory
 *
 * The top-level `translations/` directory contains **only** `.pot` templates,
 * `.po` translated files, and their `.json` manifests (TranslationNode,
 * `$schema: "translation-node/v1"`). Rendered output (`.md`), QA sidecars
 * (`.qa.json`), and status metadata are properties of the TranslationNode
 * manifest, not loose files.
 *
 * ```
 * translations/
 *   fr/
 *     index.json          ← TranslationNode manifest (KG node)
 *     index.pot           ← POT template (extractable strings)
 *     index.po            ← PO translated strings
 *     agent-onboarding.json
 *     agent-onboarding.pot
 *     agent-onboarding.po
 *     glossary.json       ← shared glossary PO (no POT — hand-authored)
 *     glossary.po
 * ```
 *
 * Each `.json` manifest is a `TranslationNode` that references its `.po` and
 * `.pot` siblings, so every translation file is a **node in the knowledge
 * graph**.
 *
 * ## PO source resolution (fallback behavior)
 *
 * When a content block does NOT declare `poSources[]` (the common case),
 * the pipeline resolves PO files by convention:
 *
 * 1. **Block-level:** `translations/<locale>/<block-stem>.po`
 * 2. **Chapter-level:** `translations/<locale>/<chapter-slug>.po`
 * 3. **Folio-level:** `translations/<locale>/global.po`
 * 4. **Dependency walk:** `harness.config.json` dependencies, depth-first
 *
 * When `poSources[]` IS declared on BlockBase, only the listed files are
 * consulted (no fallback). Later entries override earlier for the same msgid.
 *
 * ## Official vs unofficial
 *
 * An **official** translation has been reviewed and approved by a named human
 * for this source version. An **unofficial** translation is agentic —
 * generated by an LLM or machine translation tool. The distinction is
 * accountability, not quality.
 *
 * ## Staleness
 *
 * An official translation whose source content has changed since sign-off
 * is **stale**. The `sourceHash` field is the SHA-256 of the source `.md`
 * at sign-off time; a mismatch with the current hash sets `stale: true`. A
 * stale translation stays visible, with a warning.
 *
 * ## Sign-off levels
 *
 * A human can sign off at any level of the content hierarchy (block,
 * section, chapter, folio). The `level` field records this. A lower-level
 * sign-off overrides a higher-level one for that specific node.
 *
 * @module schemas/translation
 * @graphNode schema
 */

