/**
 * Publish the rail's shared assets — `assets/css/navbar.css` and
 * `assets/js/navbar.js`. The rail is drawn in the browser from shared data,
 * so a page carries almost no rail markup.
 *
 * - `navbar.css` is `navbarCss()` from `lib/navbar.ts`, verbatim.
 * - `navbar.js` is `navbar-client.ts` bundled: `renderRailRegions` and
 *   `navbarHtml`'s regions, the SAME code the build renders the rail with, so
 *   the browser cannot draw a different rail from the build's audit.
 *
 * Both are GENERATED, never edited, and committed; `navbar-assets.test.ts`
 * fails when either differs from what this writes. The pinned Bun version is
 * what makes a committed bundle checkable byte for byte.
 *
 *   bun run cat navbar:assets           write them
 *   bun run cat navbar:assets:check     exit 1 if either is stale
 *
 * @covers none — this asks whether two BUNDLED ASSETS and the rail data
 * beside them are current, not whether a declared graph is well-formed; the
 * graph they render is judged where it is generated (`docs:harness`), as
 * `gen-navbar-include.ts` says for the same reason.
 * @module cat-harness/scripts/gen-navbar-assets
 */
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { siteDirFor, siteFileFor } from "../schemas/kg/cat-harness.ts";
import { PIN_FILE, readPinFile } from "./check-bun-pin.ts";
import { NAVBAR_JS, RAIL_DATA_DIR, railPageOf } from "./lib/harness-rail.ts";
import { NAVBAR_CSS, navbarCss } from "./lib/navbar.ts";
import { HARNESS_ROOT } from "./lib/roots.ts";

const ROOT = join(HARNESS_ROOT);
const HEADER = (src: string) =>
  `/* GENERATED by cat-harness-tools/scripts/gen-navbar-assets.ts from ${src}.\n` +
  ` * Do not edit: \`bun run cat navbar:assets\`. */\n`;

/** `navbar.css`'s bytes. */
export function navbarCssFile(): string {
  return HEADER("navbarCss() in cat-harness/scripts/lib/navbar.ts") + navbarCss() + "\n";
}

/** `navbar.js`'s bytes: the client entry, bundled for the browser. */
export async function navbarJsFile(): Promise<string> {
  const r = await Bun.build({
    entrypoints: [join(import.meta.dir, "navbar-client.ts")],
    target: "browser",
    minify: true,
    format: "iife",
  });
  if (!r.success) throw new Error(`navbar.js: bundle failed — ${r.logs.map(String).join("; ")}`);
  return HEADER("cat-harness-tools/scripts/navbar-client.ts") + (await r.outputs[0]!.text());
}

/**
 * Why a stale `navbar.js` may be the RUNTIME rather than the file: the bundle
 * is minified, and the minifier's identifier choices change between Bun
 * releases, so a Bun other than the pinned one writes different bytes from the
 * same source. Measured 2026-10-07: Bun 1.4.2 against the 1.3.14 pin differs
 * only in minified names. Returns the sentence to print beside a stale
 * verdict, or `undefined` when the running Bun is the pinned one (or the pin
 * cannot be read, in which case there is nothing to compare). It never turns a
 * stale verdict into a pass: CI runs the pin, so the file it judges is the one
 * the pin writes.
 */
export function runtimeNote(running: string = Bun.version, repoRoot: string = join(ROOT, "..")): string | undefined {
  const pinPath = join(repoRoot, PIN_FILE);
  const pinned = existsSync(pinPath) ? readPinFile(readFileSync(pinPath, "utf-8")) : undefined;
  if (pinned === undefined || pinned === running) return undefined;
  return (
    `this is Bun ${running} but ${PIN_FILE} pins ${pinned}; the minified bundle differs between ` +
    `Bun releases, so navbar.js can read stale here and current in CI. Install ${pinned} before regenerating.`
  );
}

/** Where each is written in this checkout. */
export function navbarAssetPaths(): { css: string; js: string } {
  // The site CHROME holds both (semantic subgraphs, slice 1).
  return { css: join(ROOT, siteFileFor(ROOT, NAVBAR_CSS)), js: join(ROOT, siteFileFor(ROOT, NAVBAR_JS)) };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const paths = navbarAssetPaths();
  const want = { css: navbarCssFile(), js: await navbarJsFile() };
  let stale = 0;
  for (const k of ["css", "js"] as const) {
    const have = existsSync(paths[k]) ? readFileSync(paths[k], "utf-8") : undefined;
    if (check) {
      if (have !== want[k]) {
        console.error(`✗ ${paths[k]} is ${have === undefined ? "missing" : "stale"} — run \`bun run cat navbar:assets\``);
        stale++;
      }
    } else {
      writeFileSync(paths[k], want[k]);
      console.log(`✓ wrote ${paths[k]}`);
    }
  }
  // Rail data no committed page names any more: this generator family's own
  // stale output (a changed rail moves its pages to a new content-named file).
  // The PAGES' site directory: rail data serves the harness pages, which stay in
  // `siteDirFor`'s layer while navbar.js is the chrome's (semantic subgraphs, slice 1).
  const site = join(ROOT, siteDirFor(ROOT));
  const dataDir = join(site, RAIL_DATA_DIR);
  if (existsSync(dataDir)) {
    const named = new Set<string>();
    for (const rel of new Bun.Glob("**/*.html").scanSync({ cwd: site })) {
      const page = railPageOf(readFileSync(join(site, rel), "utf-8"));
      if (page) named.add(page.data);
    }
    for (const f of readdirSync(dataDir)) {
      if (!/^rail-[a-z0-9]+\.js$/.test(f) || named.has(f.replace(/\.js$/, ""))) continue;
      if (check) {
        console.error(`✗ ${join(RAIL_DATA_DIR, f)} is named by no page — run \`bun run cat navbar:assets\``);
        stale++;
      } else {
        rmSync(join(dataDir, f));
        console.log(`✓ removed ${join(RAIL_DATA_DIR, f)} — no page names it`);
      }
    }
  }
  if (check && stale) {
    const note = runtimeNote();
    if (note) console.error(`  note: ${note}`);
    process.exit(1);
  }
  if (check) console.log("✓ navbar.css and navbar.js match their sources");
}
